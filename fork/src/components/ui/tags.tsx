import type { EventSource, ProbabilityKind } from "@/lib/domain/types";

const KIND_TITLE: Record<ProbabilityKind, string> = {
  MARKET: "Observed: derived from a real market price",
  MODEL: "Model estimate: generated by AI analysts in this app",
  DEMO: "Demonstration: illustrative, hand-authored value",
};

export function KindTag({ kind, small = false }: { kind: ProbabilityKind; small?: boolean }) {
  const cls = kind === "MARKET" ? "tag-market tag-live" : kind === "MODEL" ? "tag-model" : "tag-demo";
  return (
    <span className={`tag ${cls}`} title={KIND_TITLE[kind]} style={small ? { height: 14, fontSize: 8.5 } : undefined}>
      {kind}
    </span>
  );
}

const SOURCE_LABEL: Record<EventSource, string> = { gemini: "Gemini", demo: "Demo", custom: "Custom", model: "Model-proposed" };

export function SourceTag({ source, small = false }: { source: EventSource; small?: boolean }) {
  const cls = source === "gemini" ? "tag-market" : source === "demo" ? "tag-demo" : source === "model" ? "tag-model" : "tag-custom";
  return (
    <span className={`tag ${cls}`} style={small ? { height: 14, fontSize: 8.5 } : undefined} title={source === "gemini" ? "Listed on Gemini Prediction Markets" : source === "demo" ? "Hypothetical demonstration event" : source === "model" ? "Question proposed by a model" : "User-defined event"}>
      {SOURCE_LABEL[source]}
    </span>
  );
}
